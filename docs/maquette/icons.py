"""Redrawn (original) line icons for the modernised palette, 24x24 viewBox.
Dots (`D`) mark the points the user designates; they take the family colour."""

def L(x1, y1, x2, y2, dash=None, w=None):
    a = f' stroke-dasharray="{dash}"' if dash else ''
    b = f' stroke-width="{w}"' if w else ''
    return f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"{a}{b}/>'
def C(cx, cy, r, dash=None):
    a = f' stroke-dasharray="{dash}"' if dash else ''
    return f'<circle cx="{cx}" cy="{cy}" r="{r}"{a}/>'
def E(cx, cy, rx, ry, rot=0):
    return f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" transform="rotate({rot} {cx} {cy})"/>'
def R(x, y, w, h, rx=0, dash=None):
    a = f' stroke-dasharray="{dash}"' if dash else ''
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}"{a}/>'
def P(d, dash=None, fill=None):
    a = f' stroke-dasharray="{dash}"' if dash else ''
    f = f' fill="{fill}"' if fill else ''
    return f'<path d="{d}"{a}{f}/>'
def D(x, y, r=1.7):
    return f'<circle cx="{x}" cy="{y}" r="{r}" style="fill: var(--fam, #22a05a); stroke: none"/>'
def T(x, y, s, size=9, weight=600, anchor='middle', italic=False, serif=False):
    st = ' font-style="italic"' if italic else ''
    ff = 'Georgia, serif' if serif else 'Inter, system-ui, sans-serif'
    return (f'<text x="{x}" y="{y}" font-size="{size}" font-weight="{weight}" text-anchor="{anchor}"'
            f' font-family="{ff}" fill="currentColor" stroke="none"{st}>{s}</text>')
def AH(x, y, ang):
    """small arrow head at (x,y) pointing to angle (deg)."""
    import math
    a = math.radians(ang); l = 3.2; s = math.radians(28)
    p1 = (x - l * math.cos(a - s), y - l * math.sin(a - s)); p2 = (x - l * math.cos(a + s), y - l * math.sin(a + s))
    return f'<path d="M{p1[0]:.1f} {p1[1]:.1f} L{x} {y} L{p2[0]:.1f} {p2[1]:.1f}"/>'
def DIMH(x1, x2, y):
    return L(x1, y, x2, y) + AH(x1, y, 180) + AH(x2, y, 0)
def HATCH(x, y, w, h, step=3.5):
    out = []
    k = -h
    while k < w:
        xa, ya = x + max(k, 0), y + h - max(0, -k)
        xb, yb = x + min(k + h, w), y + h - min(h, w - k)
        out.append(L(round(xa, 1), round(ya, 1), round(xb, 1), round(yb, 1), w=1))
        k += step
    return ''.join(out)

